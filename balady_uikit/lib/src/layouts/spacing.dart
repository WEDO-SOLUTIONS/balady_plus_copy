/// Represents spacing values used in UI layout.
/// Currently we are moving to the Design 3.0 and we should use only values from
/// Design 3.0 and do not use deprecated ones
class Spacing {
  /// Zero value of spacing
  /// Used in Design 3.0
  /// value: 0.0
  static const none = 0.0;

  /// One pixel value of spacing
  /// Used in Design 3.0
  /// value: 1.0
  static const px = 1.0;

  /// 0,5x value of spacing
  /// Used in Design 3.0
  /// value: 2.0
  static const $0_5x = 2.0;

  /// 1x value of spacing
  /// Used in Design 3.0
  /// value: 4.0
  static const $1x = 4.0;

  /// 1,5x value of spacing
  /// Used in Design 3.0
  /// value: 6.0
  static const $1_5x = 6.0;

  /// 2x value of spacing
  /// Used in Design 3.0
  /// value: 8.0
  static const $2x = 8.0;

  /// 3x value of spacing
  /// Used in Design 3.0
  /// value: 12.0
  static const $3x = 12.0;

  /// 4x value of spacing
  /// Used in Design 3.0
  /// value: 16.0
  static const $4x = 16.0;

  /// 5x value of spacing
  /// Used in Design 3.0
  /// value: 20.0
  static const $5x = 20.0;

  /// 6x value of spacing
  /// Used in Design 3.0
  /// value: 24.0
  static const $6x = 24.0;

  /// 8x value of spacing
  /// Used in Design 3.0
  /// value: 32.0
  static const $8x = 32.0;

  /// 10x value of spacing
  /// Used in Design 3.0
  /// value: 40.0
  static const $10x = 40.0;

  /// 12x value of spacing
  /// Used in Design 3.0
  /// value: 48.0
  static const $12x = 48.0;

  /// 16x value of spacing
  /// Used in Design 3.0
  /// value: 64.0
  static const $16x = 64.0;
}
