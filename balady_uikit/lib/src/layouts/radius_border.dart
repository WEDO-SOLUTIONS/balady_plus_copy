/// Class representing border radius values.
/// Design version 3.0
class RadiusBorder {
  /// Base sharp border radius value.
  static const baseSharp = 8.0;

  /// Full sharp border radius value.
  static const full = 999.0;

  /// Zero value for border radius.
  static const none = 0.0;

  /// Extra Extra Small value of border radius.
  static const xxs = 2.0;

  /// Extra Small value of border radius.
  static const xs = 4.0;

  /// Small value of border radius.
  static const s = 6.0;

  /// Medium value of border radius.
  static const m = baseSharp;

  /// Medium Large value of border radius.
  static const ml = 10.0;

  /// Large value of border radius.
  static const l = 12.0;

  /// Extra Large value of border radius.
  static const xl = 16.0;

  /// Extra Extra Large value of border radius.
  static const xxl = 24.0;
}
