List<Widget> getIconSet(
  String title,
  Map<String, Icon> icons,
  double mainAxisSpacing,
  double maxCrossAxisExtent,
  double childAspectRatio,
  double crossAxisSpacing,
  double mainAxisExtent,
  bool showBorders,
) =>
    [
      const SliverPadding(
        padding: EdgeInsets.all(10),
      ),
      SliverToBoxAdapter(
        child: Text(
          title,
          style: const TextStyle(fontSize: 32),
        ),
      ),
      SliverGrid(
        delegate: SliverChildBuilderDelegate(
          childCount: icons.length,
          (context, index) {
            final entry = icons.entries.toList()[index];
            final icon = entry.value;
            return Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                DecoratedBox(
                  decoration: BoxDecoration(border: showBorders ? Border.all(color: Colors.purple) : null),
                  child: icon,
                ),
                const SizedBox(
                  width: 10,
                ),
                Text(entry.key,
                    softWrap: true,
                    maxLines: 2,
                    style: context.textStyles.h4SemiBold.copyWith(
                      color: context.colors.foregroundDefault,
                      // color: Colors.black,
                    )),
              ],
            );
          },
        ),
        gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
          mainAxisExtent: 64,
          crossAxisCount: 2,
        ),
      ),
    ];
