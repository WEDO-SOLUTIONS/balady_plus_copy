#!/usr/bin/env python3
"""Inline the mini game into a single distributable HTML file.

The multi-file version under css/ and js/ stays the source of truth; this
script folds it into dist/drift-the-desert.html so the game can be handed to a
reviewer as one attachment, dropped into a WebView that only accepts a single
document, or opened straight from file:// with no server.

Usage:  python3 build_standalone.py
"""

import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'dist' / 'drift-the-desert.html'

# A literal </script> inside inlined JS would close the tag early. None of our
# sources contain one today, but a future edit must not silently break the build.
CLOSING_TAG = re.compile(r'</\s*script', re.IGNORECASE)


def read(rel: str) -> str:
    path = ROOT / rel
    if not path.is_file():
        sys.exit(f'missing source file: {rel}')
    return path.read_text(encoding='utf-8')


def guard(js: str, name: str) -> str:
    return CLOSING_TAG.sub(lambda m: m.group(0).replace('<', '\\x3C'), js) if CLOSING_TAG.search(js) else js


def main() -> None:
    html = read('index.html')

    # <link rel="stylesheet" href="css/style.css"> -> inline <style>
    link = re.search(r'[ \t]*<link rel="stylesheet" href="([^"]+)"[^>]*>\s*\n', html)
    if not link:
        sys.exit('could not find the stylesheet link in index.html')
    css = read(link.group(1))
    html = html[:link.start()] + f'<style>\n{css}</style>\n' + html[link.end():]

    # each <script src="js/*.js"></script> -> inline <script>
    def inline(match: re.Match) -> str:
        src = match.group(1)
        return f'<script>\n{guard(read(src), src)}</script>'

    html, count = re.subn(r'<script src="([^"]+)"></script>', inline, html)
    if count == 0:
        sys.exit('could not find any script tags in index.html')

    stamp = (
        '<!--\n'
        '  Drift the Desert - Balady+ Maps.\n'
        '  Single-file build generated by build_standalone.py on '
        f'{date.today().isoformat()}.\n'
        '  Do not edit: change the sources in assets/games/drift_the_desert/\n'
        '  (index.html, css/style.css, js/*.js) and re-run the script.\n'
        '-->\n'
    )
    html = html.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + stamp, 1)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding='utf-8')

    print(f'{OUT.relative_to(ROOT.parent.parent.parent)}  '
          f'{len(html.encode("utf-8")) / 1024:.0f} KB  '
          f'(1 stylesheet + {count} scripts inlined)')


if __name__ == '__main__':
    main()
