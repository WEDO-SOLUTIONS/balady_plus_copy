#!/usr/bin/env python3
"""Merge committed l10n overrides into the Localazy-downloaded ARB files.

Run AFTER `localazy download` and BEFORE `flutter gen-l10n`.

Why this exists: some keys are referenced in code but are not published in
Localazy (e.g. the project is over its key-plan limit, so newly uploaded keys
stay unpublished). The ARB files are gitignored and regenerated by
`localazy download`, so a direct edit does not survive. This script re-applies
the overrides from `mapness/l10n_overrides.json` on every generation, in CI and
locally, so the build always compiles.

Idempotent: an override only fills a key that is missing; it never clobbers a
translation that Localazy already provides (once a key is published in Localazy,
delete it from the overrides file).
"""
import json
import os
import sys

# Repo-root-relative paths (the script is invoked from the repo root).
OVERRIDES = "mapness/l10n_overrides.json"
ARB_DIR = "mapness/lib/l10n"


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    if not os.path.exists(OVERRIDES):
        print(f"[l10n-overrides] no overrides file at {OVERRIDES}; nothing to do.")
        return 0

    overrides = load_json(OVERRIDES)
    applied_total = 0

    for lang, entries in overrides.items():
        if lang.startswith("_"):  # skip _comment and similar meta keys
            continue
        arb_path = os.path.join(ARB_DIR, f"app_{lang}.arb")
        if not os.path.exists(arb_path):
            print(f"[l10n-overrides] WARN: {arb_path} not found; skipping '{lang}'.")
            continue

        arb = load_json(arb_path)
        applied = 0
        for key, value in entries.items():
            if key not in arb or not str(arb.get(key, "")).strip():
                arb[key] = value
                applied += 1

        if applied:
            # Keep keys sorted so the file matches Localazy's deterministic output.
            ordered = dict(sorted(arb.items()))
            with open(arb_path, "w", encoding="utf-8") as f:
                json.dump(ordered, f, ensure_ascii=False, indent=2)
                f.write("\n")
            applied_total += applied
        print(f"[l10n-overrides] {lang}: applied {applied} override(s) -> {arb_path}")

    print(f"[l10n-overrides] done. {applied_total} override(s) applied in total.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
