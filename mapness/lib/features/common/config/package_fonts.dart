import 'package:flutter/material.dart';

class PackageFonts {
  static TextStyle frutigerArabic({
    Color? color,
    double? fontSize,
    FontWeight? fontWeight,
    FontStyle? fontStyle,
    double? height,
  }) =>
      TextStyle(
        color: color,
        fontSize: fontSize,
        fontWeight: fontWeight,
        fontStyle: fontStyle,
        height: height,
        fontFamily: "Frutiger LT Arabic",
      );
}
