part 'search_region_bound_provider.g.dart';

/// A [FutureProvider] that fetches the viewport bounds (region polygon)
/// for the current user location.
///
/// This provider is designed to retrieve a bounding polygon (e.g., for map
/// zoom or filtering) by sending the user's current coordinates to a remote
/// geocoding API.
///
/// It internally depends on:
/// - [vendorConfigProvider]: to get API endpoints and keys.
/// - [baseDioProvider]: to perform HTTP requests.
/// - [locationProvider]: to get the current user location.
///
/// The request is sent to the endpoint generated by
/// [BaldayDeeplink.searchBoundRegion] using the coordinates from
/// [locationProvider]. The API is expected to return a polygon
/// representing the regional bounds around the given coordinates.
///
/// Returns a [SearchRegionPolygon] representing the bounds.

@riverpod
class SearchRegionBound extends _$SearchRegionBound {
  @override
  Future<SearchRegionPolygon> build({
    required double longitude,
    required double latitude,
  }) async {
    try {
      final vendorConfig = await ref.read(vendorConfigProvider.future);
      final dio = ref.read(baseDioProvider);

      final catalogApi = vendorConfig[BaldayDeeplink.catalogKey];
      final key = vendorConfig[BaldayDeeplink.vendorConfigKey];

      final geocodeUrl = BaldayDeeplink.searchBoundRegion(catalogApi);
      var lon = longitude;
      var lat = latitude;
      if (lon == 0 || lat == 0) {
        final location = ref.read(locationProvider);
        lon = location?.longitude ?? longitude;
        lat = location?.latitude ?? latitude;
      }

      final response = await dio.get(
        geocodeUrl,
        queryParameters: {
          BaldayDeeplink.qKey: '$lon,$lat',
          BaldayDeeplink.fieldsKey: BaldayDeeplink.fieldsValueBounds,
          BaldayDeeplink.keyKey: key,
        },
      );

      final data = response.data as Map<String, dynamic>;
      final result = data['result'] as Map<String, dynamic>;
      final firstItem = result['items'][0] as Map<String, dynamic>;

      return SearchRegionPolygon.fromJson(firstItem);
    } catch (e) {
      rethrow;
    }
  }

  bool get isRiyadh => state.value?.id == '216';
}
